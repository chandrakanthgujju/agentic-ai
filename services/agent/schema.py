"""Convert MCP tool definitions into Bedrock Converse ``toolSpec`` entries.

MCP tools publish JSON Schema generated by pydantic. The Bedrock Converse API
passes that schema to the model provider, and providers differ in how much of
JSON Schema they accept. Amazon Nova is the strictest of the three models this
app offers: its user guide says Nova "supports only a subset of JsonSchema
functionality" for ``ToolInputSchema`` - the top level may contain only
``type`` (``"object"``), ``properties`` and ``required`` - and Nova tool names
must match ``[a-zA-Z][a-zA-Z0-9_]*``. Schemas outside that subset are rejected
with a ``ValidationException`` before any token is generated.

So we emit one conservative schema that every allowlisted model accepts:

* top level: exactly ``type``/``properties``/``required``;
* each property: ``type``, ``description``, ``enum``, ``items`` and nested
  ``properties``/``required`` only;
* ``anyOf: [X, null]`` (pydantic's ``Optional[X]``) collapses to ``X`` -
  optionality is already expressed by ``required``;
* validation keywords (``pattern``, ``minimum``, ``maxLength``, ``default`` ...)
  are moved into the property description as plain-English hints, so the
  model still sees them. The MCP server re-validates every argument, so no
  constraint is lost - a bad argument comes back as a tool error.
"""

from __future__ import annotations

import json
import re
from typing import Any

# Strictest tool-name rule among the allowlisted models (Amazon Nova).
TOOL_NAME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9_]{0,63}$")
_DESCRIPTION_LIMIT = 1000
_JSON_TYPES = {"string", "number", "integer", "boolean", "array", "object"}

# Keywords that are kept as hints in the description instead of as schema.
_HINTS = (
    ("pattern", "format: regex {}"),
    ("format", "format: {}"),
    ("minimum", "minimum {}"),
    ("maximum", "maximum {}"),
    ("exclusiveMinimum", "greater than {}"),
    ("exclusiveMaximum", "less than {}"),
    ("minLength", "at least {} characters"),
    ("maxLength", "at most {} characters"),
    ("minItems", "at least {} items"),
    ("maxItems", "at most {} items"),
    ("default", "default {}"),
)


class InvalidToolError(ValueError):
    """A tool that no allowlisted model can accept (it is skipped, not fatal)."""


def _collapse_optional(node: dict) -> dict:
    any_of = node.get("anyOf")
    if not isinstance(any_of, list):
        return node
    non_null = [s for s in any_of if not (isinstance(s, dict) and s.get("type") == "null")]
    if len(non_null) == 1 and isinstance(non_null[0], dict):
        merged = {k: v for k, v in node.items() if k != "anyOf"}
        merged.update(non_null[0])
        return merged
    return node


def _property_schema(node: Any) -> dict:
    if not isinstance(node, dict):
        return {"type": "string"}
    node = _collapse_optional(node)
    out: dict[str, Any] = {}

    node_type = node.get("type")
    if isinstance(node_type, list):  # e.g. ["string", "null"]
        node_type = next((t for t in node_type if t != "null"), None)
    if node_type not in _JSON_TYPES:
        node_type = "object" if "properties" in node else ("array" if "items" in node else "string")
    out["type"] = node_type

    hints = []
    for key, template in _HINTS:
        value = node.get(key)
        if value is None:
            continue
        hints.append(template.format(json.dumps(value) if not isinstance(value, str) else value))
    description = str(node.get("description") or "").strip()
    if hints:
        description = f"{description} ({'; '.join(hints)})".strip()
    if description:
        out["description"] = description[:_DESCRIPTION_LIMIT]

    enum = node.get("enum")
    if isinstance(enum, list):
        values = [v for v in enum if v is not None]
        if values:
            out["enum"] = values
    if node_type == "array":
        out["items"] = _property_schema(node.get("items") or {"type": "string"})
    if node_type == "object" and isinstance(node.get("properties"), dict):
        out["properties"] = {k: _property_schema(v) for k, v in node["properties"].items()}
        required = [r for r in node.get("required", []) if r in out["properties"]]
        if required:
            out["required"] = required
    return out


def to_input_schema(input_schema: dict | None) -> dict:
    """Return a top-level object schema limited to type/properties/required."""
    schema = input_schema or {}
    if "$ref" in json.dumps(schema):
        # pydantic emits $defs/$ref for nested models; none of our tools use them and
        # Nova rejects them. Fail loudly at discovery time rather than at chat time.
        raise InvalidToolError("tool input schema uses $ref/$defs, which Amazon Nova does not accept")
    properties = schema.get("properties") if isinstance(schema.get("properties"), dict) else {}
    out: dict[str, Any] = {"type": "object", "properties": {k: _property_schema(v) for k, v in properties.items()}}
    required = [r for r in schema.get("required", []) if r in out["properties"]]
    if required:
        out["required"] = required
    return out


def to_bedrock_tool_spec(name: str, description: str | None, input_schema: dict | None) -> dict:
    if not TOOL_NAME_RE.match(name or ""):
        raise InvalidToolError(f"tool name '{name}' must match {TOOL_NAME_RE.pattern} for Bedrock/Nova")
    return {
        "toolSpec": {
            "name": name,
            "description": (description or name).strip()[:_DESCRIPTION_LIMIT],
            "inputSchema": {"json": to_input_schema(input_schema)},
        }
    }
