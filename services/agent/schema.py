"""Convert MCP tool definitions into Bedrock Converse ``toolSpec`` entries.

MCP tools publish JSON Schema generated by pydantic. Bedrock models accept JSON
Schema too, but smaller models are stricter about some constructs, so we
normalise: drop ``title`` noise and collapse ``anyOf: [X, null]`` (pydantic's
encoding of ``Optional[X]``) to ``X``. Optionality is already expressed by the
field not being in ``required``.
"""

from __future__ import annotations

import re
from typing import Any

_NAME_RE = re.compile(r"^[a-zA-Z0-9_-]{1,64}$")
_DESCRIPTION_LIMIT = 1000


def simplify_schema(node: Any) -> Any:
    if isinstance(node, list):
        return [simplify_schema(n) for n in node]
    if not isinstance(node, dict):
        return node
    node = {k: v for k, v in node.items() if k != "title"}
    any_of = node.get("anyOf")
    if isinstance(any_of, list):
        non_null = [s for s in any_of if not (isinstance(s, dict) and s.get("type") == "null")]
        if len(non_null) == 1 and len(non_null) != len(any_of):
            merged = {k: v for k, v in node.items() if k != "anyOf"}
            merged.update(non_null[0])
            node = merged
    return {k: simplify_schema(v) for k, v in node.items()}


def to_bedrock_tool_spec(name: str, description: str | None, input_schema: dict) -> dict:
    if not _NAME_RE.match(name):
        raise ValueError(f"tool name '{name}' is not valid for Bedrock")
    schema = simplify_schema(input_schema or {"type": "object", "properties": {}})
    schema.setdefault("type", "object")
    schema.setdefault("properties", {})
    return {
        "toolSpec": {
            "name": name,
            "description": (description or name)[:_DESCRIPTION_LIMIT],
            "inputSchema": {"json": schema},
        }
    }
